/**
 * Inline the proposal's CSS and JS into one self-contained HTML file.
 * Usage: node design/build.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, "src");
const htmlPath = join(src, "index.html");
const cssPath = join(src, "styles.css");
const jsPath = join(src, "app.js");
const outPath = join(here, "FlashManager-SugarStar-Design-Proposal.html");

const html = readFileSync(htmlPath, "utf8");
const avatarCss = readFileSync(join(src, "avatar-assets.css"), "utf8");
let css = readFileSync(cssPath, "utf8");
css = css.replace('@import url("./avatar-assets.css");', () => avatarCss);
if (css.includes('@import url("./avatar-assets.css")')) {
  throw new Error("Failed to inline avatar-assets.css");
}
const js = readFileSync(jsPath, "utf8");

const styleMarker = '<link rel="stylesheet" href="./styles.css" />';
const scriptMarker = '<script src="./app.js" defer></script>';

if (!html.includes(styleMarker) || !html.includes(scriptMarker)) {
  throw new Error("Build markers not found. Did index.html change?");
}

let out = html.replace(styleMarker, () => `<style>\n${css}\n</style>`);
out = out.replace(scriptMarker, () => `<script>\n${js}\n</script>`);
out = out.replace(
  "</head>",
  `  <!-- Self-contained build · generated from design/src. Do not edit this file directly. -->\n</head>`
);

if (out.includes(styleMarker) || out.includes(scriptMarker)) {
  throw new Error("Build failed to inline every asset.");
}

writeFileSync(outPath, out, "utf8");
console.log(`built ${outPath}`);
console.log(`size  ${(Buffer.byteLength(out) / 1024).toFixed(1)} KB`);
